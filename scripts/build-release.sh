#!/usr/bin/env bash
# Build immutable backend/frontend images and emit an exact compose override.
#
# Usage:
#   scripts/build-release.sh
#   scripts/build-release.sh --push
#
# Required for a push: docker login registry.sxueji.com
# Optional:
#   HEMALL_RELEASE_REGISTRY=registry.sxueji.com/hemall
#   HEMALL_RELEASE_OUTPUT_DIR=/data/soffy/releases/hemall
#   NEXT_PUBLIC_API_URL=https://mall.sxueji.com

set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
REGISTRY="${HEMALL_RELEASE_REGISTRY:-registry.sxueji.com/hemall}"
OUTPUT_ROOT="${HEMALL_RELEASE_OUTPUT_DIR:-$ROOT/release}"
API_URL="${NEXT_PUBLIC_API_URL:-https://mall.sxueji.com}"
CHATWOOT_BASE_URL="${NEXT_PUBLIC_CHATWOOT_BASE_URL:-}"
CHATWOOT_WEBSITE_TOKEN="${NEXT_PUBLIC_CHATWOOT_WEBSITE_TOKEN:-}"
PUSH=0

case "${1:-}" in
  "") ;;
  --push) PUSH=1 ;;
  -h|--help)
    sed -n '2,17p' "$0" | sed 's/^# \{0,1\}//'
    exit 0
    ;;
  *)
    echo "未知参数: $1 (只支持 --push)" >&2
    exit 2
    ;;
esac

cd "$ROOT"
command -v docker >/dev/null || { echo "docker 未安装" >&2; exit 1; }
docker buildx version >/dev/null 2>&1 || { echo "docker buildx 不可用" >&2; exit 1; }

GIT_SHA="${HEMALL_RELEASE_GIT_SHA:-$(git rev-parse HEAD)}"
if [[ ! "$GIT_SHA" =~ ^[0-9a-f]{40}$ ]]; then
  echo "git sha 必须是完整 40 位小写十六进制: $GIT_SHA" >&2
  exit 1
fi

if [[ "${HEMALL_RELEASE_ALLOW_DIRTY:-0}" != "1" ]] \
  && [[ -n "$(git status --porcelain --untracked-files=normal)" ]]; then
  echo "工作树不干净；发布镜像必须对应可追溯 commit。提交后重试。" >&2
  echo "仅本地演练可设 HEMALL_RELEASE_ALLOW_DIRTY=1。" >&2
  exit 1
fi

BUILT_AT="$(date -u '+%Y-%m-%dT%H:%M:%SZ')"
BACKEND_IMAGE="${REGISTRY}/backend:sha-${GIT_SHA}"
FRONTEND_IMAGE="${REGISTRY}/frontend:sha-${GIT_SHA}"
OUT_DIR="${OUTPUT_ROOT}/${GIT_SHA}"
mkdir -p "$OUT_DIR"

build_image() {
  local name="$1"
  shift
  echo "==> build ${name}"
  docker buildx build \
    --load \
    --build-arg "GIT_SHA=${GIT_SHA}" \
    --build-arg "BUILD_CREATED=${BUILT_AT}" \
    "$@"
}

build_image backend \
  -f Dockerfile.prod \
  -t "$BACKEND_IMAGE" \
  .

build_image frontend \
  -f web/Dockerfile \
  --build-arg "NEXT_PUBLIC_API_URL=${API_URL}" \
  --build-arg "NEXT_PUBLIC_CHATWOOT_BASE_URL=${CHATWOOT_BASE_URL}" \
  --build-arg "NEXT_PUBLIC_CHATWOOT_WEBSITE_TOKEN=${CHATWOOT_WEBSITE_TOKEN}" \
  -t "$FRONTEND_IMAGE" \
  web

verify_revision() {
  local image="$1"
  local revision
  revision="$(docker image inspect "$image" \
    --format '{{index .Config.Labels "org.opencontainers.image.revision"}}')"
  if [[ "$revision" != "$GIT_SHA" ]]; then
    echo "镜像 ${image} 的 revision=${revision}，期望 ${GIT_SHA}" >&2
    exit 1
  fi
}

verify_revision "$BACKEND_IMAGE"
verify_revision "$FRONTEND_IMAGE"

cat > "$OUT_DIR/release.env" <<EOF
GIT_SHA=${GIT_SHA}
BUILT_AT=${BUILT_AT}
BACKEND_IMAGE=${BACKEND_IMAGE}
FRONTEND_IMAGE=${FRONTEND_IMAGE}
NEXT_PUBLIC_API_URL=${API_URL}
NEXT_PUBLIC_CHATWOOT_BASE_URL=${CHATWOOT_BASE_URL}
EOF

cat > "$OUT_DIR/docker-compose.release.yml" <<EOF
# Generated by scripts/build-release.sh. Both images are pinned to the exact
# source revision; do not edit or replace with a floating tag.
services:
  api:
    image: ${BACKEND_IMAGE}
  web:
    image: ${FRONTEND_IMAGE}
EOF

cat > "$OUT_DIR/manifest.json" <<EOF
{
  "git_sha": "${GIT_SHA}",
  "built_at": "${BUILT_AT}",
  "backend_image": "${BACKEND_IMAGE}",
  "frontend_image": "${FRONTEND_IMAGE}",
  "next_public_api_url": "${API_URL}"
}
EOF

if (( PUSH )); then
  echo "==> push ${BACKEND_IMAGE}"
  docker push "$BACKEND_IMAGE"
  echo "==> push ${FRONTEND_IMAGE}"
  docker push "$FRONTEND_IMAGE"
fi

echo
echo "发布产物: $OUT_DIR"
echo "后端: $BACKEND_IMAGE"
echo "前端: $FRONTEND_IMAGE"
echo "compose override: $OUT_DIR/docker-compose.release.yml"
if (( PUSH == 0 )); then
  echo "镜像仅在本机；上线前加 --push 或手动 docker push。"
fi
